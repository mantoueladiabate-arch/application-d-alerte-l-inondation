      <section id="component-info-box">
        <h3 class="page-header"><a href="#component-info-box">II- ACTIVITE SOCIO-ECONOMIQUE</a></h3>

        <p class="lead">Cocody est considérée comme une commune résidentielle. Elle est réputée pour ses maisons de haut et moyen standing des quartiers résidentiels
          tels Deux-Plateaux, Riviera, Angré, Riviera Palmeraie, Riviera Golf, la 7eme Tranche. C’est l’une des communes qui disposent 
          d’importants infrastructures scolaires et universitaires, la grande majorité des ambassades, des hôtels de prestige, de nombreuses entreprises et 
          de infrastructures sanitaires.</p>

        <p>Ses habitats sont très diversifiés. Il y en a de types haut standing, moyen standing ou bas standing. Il est constitué de maisons modernes 
          individuelles (villa), d’habitats logements en bandes, d'immeubles collectifs, de concessions, de cases traditionnelles (plusieurs villages) de baraques 
          et d’habitats collectif construits dans le cadre d’opérations immobilières. Toutefois, les constructions modernes contrastent avec des poches d’habitats 
          précaires construits en banco et/ou en matériaux de récupération. Ces habitats sont généralement dépourvus d’infrastructures socioéconomiques de base, 
          parce que difficiles d’accès en raison de leur localisation dans des zones non constructibles.</p>

        <p class="lead">Sa population qui est de 447 055 habitants dont 207 382 hommes et 239 673 femmes  avec une densité de son espace urbanisé s’élève
          à 3 387 habitants/km2 selon le RGPH, 2014 est composée d’autochtones les Ebriés et de presque toutes les communautés d’origine ivoirienne 
          tels que les Agni, les Alladian, les Attié, les Baoulé, les Bété, les Dida, les Malinké, les Yacouba, les Sénoufo, les Wobé et les Guéré  etc., 
          ainsi que de ressortissants de pays étrangers, notamment les Burkinabè, les Béninois, les Ghanéens, les Guinéens, les Maliens, les Mauritaniens, 
          les Nigériens, les Nigérians, les Sénégalais, les Togolais, les Libanais, les européens etc.  </p>
        <p>Le revenu annuel moyenne par individu selon INS est de 1.264.002 avec une taille moyenne des ménages de 4,5. </p>
      
