              <p class="lead">
              La carte de sensibilité à l'inondation est élaborée à partir de la matrice de sensibilité 
              obtenue avec les pentes, la densité du réseau d'assainissement et la densité de drainage. Elle met en évidence cinq zones (figure). 
             </p>
             <img src="data/sensibilite.png"/>
             <p >
             Figure : Carte de sensibilité à l’inondation
              </p>
              <p >
              La classe très faible est concentrée au centre et couvre 23.08 % de la surface communale et a une superficie de 30 km2.
               Il s’agit essentiellement des zones à faible pente et très forte drainage. Il s’agit entre autres des quartiers de la Rivera palmeraie, 
               7eme Tranche, Attoban.
              </p>
              <p >
              La classe faible quant à elle occupe une partie assez considérable 28.46% soit 37 Km2 de la zone d’étude.  Elle se trouve aux alentours 
              des zones à très faible sensibilité. Cette classe est caractérisée par une forte densité de drainage, une faible isohyète et dominée par 
              une pente très faible.
              </p>
              <p >
              La classe moyenne est dominante au Nord avec 26.15 % avec une superficie de 34 km2. Elle dominante par de forte très forte pente et une isohyète moyenne.
              </p>
              <p >
              La classe de forte sensibilité occupe une proportion de 14.62 % dans la zone d'étude. Cette zone est marquée par une pente très faible, 
              une forte densité de drainage des eaux et une forte isohyète. Elle se site au Nord-Est et Sud-Ouest entre les zones très forte et moyenne.
              </p>
              <p >
              La classe de très forte sensibilité se trouve en grande partie au Sud-Ouest de la zone d'étude avec les quartiers comme Rivera Golf II, Danga,
              Valdoyen, La Canebière, Ambassades, Cocody Centre. Elle est caractérisée par une très forte isohyète, une forte densité de drainage 
              des eaux et une faible pente. Cette plage occupe 7.69 % et occupe 10Km2 de la zone d'étude. 
              </p>
