        sèche d’août à septembre, une petite saison des pluies d’octobre à novembre, et une grande saison sèche de décembre à mai. 
        </p>
        <p class="lead">
        D’une manière générale, ce climat se caractérise par une abondance de précipitations. La précipitation moyenne mensuelle (figure) 
        varie de 22 à 534 mm avec une moyenne interannuelle de 149,33 mm. Les précipitations les plus faibles sont de 22 et 49 mm 
        respectivement en janvier et en août. Les plus fortes sont 534 et 267 des mois de juin et mai.   
