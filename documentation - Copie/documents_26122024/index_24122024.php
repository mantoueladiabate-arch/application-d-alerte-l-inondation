          <h4 class="page-header"><a href="#component-control-sidebar">I.8- Caractéristique géologique </br> et pédologique de la zone d’étude</a></h4>

          <p class="lead">TAbidjan tout comme la commune de Cocody appartient au bassin sédimentaire tertiaire de Côte d'Ivoire. 
            C’est une étroite bande de terrains de texture sablo-argileux qui s'étend en Basse Côte entre les formations des lagunes 
            au Sud et le socle cristallin au Nord (Verniere, 1966). Elle se trouve dans une zone de contact qui est 
            le socle affleurant à 2 kilomètres du nord de Sassandra. </p>

          <p>La commune de Cocody est dominée au Nord comme au Sud par les sols argileux avec des éléments minéraux fortement dissociés.
            On y rencontre également des sols de formation fluvio-lagunaire.</p>

          <p>TLa géologie de l’ensemble du territoire ivoirien est marquée par un étroit bassin sédimentaire d’âge Crétacée Quartenaire
            qui s’étend de Fresco à la frontière sud du pays. Ce bassin sédimentaire représente 3% de la superficie totale de la Côte d’Ivoire 
            et s’étend sur environ 40 km ; tout le reste du paysage géologique (97% de la superficie totale) est constitué de socle précambrien (Biémi, 1992)</p>

          <p>Le district d’Abidjan y compris la commune Cocody appartient à ce bassin sédimentaire qui présente une géologie simple : 
            d’argiles et d’argiles sableuses, de sables et de grès, de conglomérats, de sables glauconieux et de marnes (Tastet, 1979).</p>
