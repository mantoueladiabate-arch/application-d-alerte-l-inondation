              Pour les cardinalités (0,1) ou (1,1) vers (0, n) ou (1, n) l’association disparait. 
              La clé de la table relative à la cardinalité (0, n) ou (1, n) migre vers la table relative à les cardinalités
             (0,1) ou (1,1) pour être une clé étrangère.  
              </p>
              <p class="lead"> 
              L’association devient une table avec comme clé la concaténation les clés primaires des deux tables lorsque 
              les cardinalités sont (0, n) ou (1, n) vers (0, n) ou (1, n).
              </p>

