    <section id="introduction">
      <h1 class="page-header"><a href="#introduction"><b>Introduction</b></a></h1>
        <p 1lass="lead">
          Notre planète subit l’impact croissant des catastrophes résultant des aléas 
          naturels et des vulnérabilités. La conjonction de ces phénomènes a des conséquences néfastes sur la vie 
          et les moyens de subsistance des populations (infrastructures, cultures vivrières, cultures de rente etc.)   
        </p>
        <p class="lead">
          La Côte d’Ivoire n’échappe malheureusement pas à cette réalité. En effet, les pluies diluviennes qui se sont
          abattues sur ce pays en 2014 et en 2016 ont coûté la vie respectivement à 39 et 16 personnes. Abidjan, la capitale
          économique de la Côte d’Ivoire subit ce phénomène qui menace son développement économique, ses infrastructures et 
          ses habitants. Les intempéries enregistrées dans cette mégalopole en 2017 montrent à quel point la protection contre 
          les inondations est devenue un enjeu majeur.
        </p>
     
        <p class="lead">
          L’urbanisation joue également un rôle important dans la survenue de l’inondation. À cet effet, NICHOLLS et al. (2008),
          affirment que l'urbanisation galopante couplée à l'évolution du climat pourrait entraîner un triplement du nombre de 
          personnes exposées à des inondations dans le monde d'ici 2070.
        </p>  
        <p class="lead">
          Cocody, commune huppée d’Abidjan n’échappe pas à ce phénomène d’inondation. Ces dernières années, cette commune a connu
          des pluies diluviennes qui ont provoqué de nombreux dégâts. En 2017, par exemple, Cocody a enregistré la mort de 7 
          personnes et de plusieurs dizaines autres évacuées de leurs maisons, 20 personnes et coûté près de 18 milliards de 
          francs CFA (27 millions d’euros) de pertes et dommages en 2018 et en 2020 721 ménages sinistrés, soit 3 605 personnes
          affectées, 9 blessés et 19 décès (Abidjan.net, 2017, 2018 et 2020). Par conséquent, l’étude du risque d’inondation 
          dans la commune de Cocody se justifie par une vulnérabilité qui augmente fortement avec le développement urbain dans 
          les zones inondables et par l’émergence de situations de risque auparavant inexistant.
        </p>
        <p class="lead">
          Pour remédier à ce problème, l’amélioration de la prévision des inondations restent des outils essentiels pour 
          l’État dans la lutte contre ce phénomène. Une meilleure information des populations exposées et la réduction de la
          vulnérabilité des biens situés dans les zones inondables sont à privilégier. Cependant, si l’État et les communes 
          ont des responsabilités dans ce domaine, chaque citoyen doit aussi contribuer à sa manière à se protéger efficacement
          afin de réduire sa propre vulnérabilité.
        </p>
        
      </section><!-- /#introduction -->


