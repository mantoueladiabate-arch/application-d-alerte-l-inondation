      <section id="contexte">
        <h1 class="page-header"><a href="#contexte"><b>Contexte et justification</b></a></h1>
        <p class="lead">
          Les inondations sont les catastrophes naturelles qui préoccupent le plus les autorités et les populations abidjanaises.
          Dès lors, qu’aucune politique restrictive (contraignante) n’est imposée au citoyen pour s’installer, il a toujours accepté 
          d'encourir les risques, tout en s’efforçant d’en minimiser les méfaits. La délimitation des zones inondables, les méthodes 
          de prévisions, les plans d'assistance et de réparation des dégâts sont quelques-uns des efforts des Ministères et des Mairies 
          en charge du dossier soit pour prévenir, soit pour venir en aide aux victimes. Pour protéger les habitants contre les 
          inondations, les pouvoirs publics mettent en place des mesures d’assainissement, telles que contrôler les inondations 
          par l’aménagement des lits et des digues, curer les caniveaux, et détourner les eaux de crue. En dépit de tous leurs efforts,
          la survenue des inondations provoque toujours de nombreux dégâts matériels et des pertes en vies humaines.
        </p>

        <p class="lead">
          Vu la complexité de la gestion de l’inondation, l’utilisation des outils informatiques est absolument nécessaire, 
          notamment les Systèmes d’Information Géographique et la Télédétection. Selon Meyer et al., 2001, la Télédétection et 
          les SIG (Systèmes d’Information Géographique) sont des outils particulièrement performants pour l’étude des risques de 
          catastrophes naturelles à l’échelle d’un vaste site ou d’une région. 
        </p>

        <p class="lead">
          A cet effet, la mise en place d’une application webmapping pourrait permettre de disposer aisément d’un éventail 
          de connaissances en rapport avec les risques d’inondation sur l’ensemble de la commune de Cocody. C’est-à-dire 
          le niveau de risques d’inondation et leurs impacts, afin de permettre une appréciation optimale des risques associés.
          </br>
          Cette stratégie de gestion du risque d’inondation à partir d’une application pourrait déterminer avec précision 
          les lieux susceptibles d’être inondés, la proportion de population à toucher ainsi que leurs biens. A cette 
          application est rattachée une base de données qui pourrait permettre de stocker des données en rapport avec 
          différents facteurs concourant à la manifestation du risque d’inondation ainsi que la modele d’analyse 
          multicritère (Analytic Hierarchy Process (AHP)) de Saaty en vue de mieux connaître le phénomène et 
          le niveau de vulnérabilité des populations. 
        </p>

        <p class="lead">
          D’où la nécessité de faire cette étude qui a pour thème « Prévision du risque d’inondation à Abidjan 
          à partir du Systèmes d’Information Géographique et la télédétection dans la commune de Cocody » afin
          de mettre en place un Système d’Information Géographique qui devra permettre de visualiser le plus 
          facilement possible toute la connaissance liée au risque d’inondation pour aboutir à une aide à 
          la gestion de l’ensemble de la commune.
          </br>
          Par ailleurs quelles seraient l’apport de ces outils et méthodes dans l’étude et 
          prévision des risques d’inondation dans la commune de Cocody ?
        </p>

        <p class="lead">
        <b> L’objectif principal</b> de cette étude est d’élaborer un Système d’information Géographique adapté à l’étude et la prévention du risque d’inondation. 
          De cet objectif principal découle trois objectifs spécifiques :
            </br>
            <ul>
            <li>	Déterminer les zones à risques d’inondation de la commune de Cocody.</li>
            </br>
            <li>	Cartographier les facteurs d’inondation dans la commune de Cocody.</li>
            </br>
            <li>	Prévenir l’inondation dans la commune de Cocody à partir du webmapping.</li>
          </ul>
        </p>

        <p class="lead">
        Notre travail s’articulera autour de trois parties : </br>
        <ul>
        <li>	Une description des caractéristiques géographique, physique, géologique, hydrogéologique, l’aspect socio-économique et 
        les conséquences de l’inondation sera effectuée ;</li></br>
        <li> Le premier partie comportera les matériels utilisés pour mener à bien cette étude. La seconde constituera la démarche méthodologique adoptée ;</li> </br>
        <li>	Une conclusion générale suivie de recommandations et de perspectives suivra; 
        Enfin nous élaborerons une discussion sur la méthodologie et des différents résultats obtenus.</li></br>
          </ul>
        </p>
      </section>


