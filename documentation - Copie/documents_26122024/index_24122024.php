            <h6 class="page-header"><a href="#dependencies">I.1.2- Traitement des images satellitaires </a></h6>
              <h5 class="page-header"><a href="#faq">I.1.2.1- Calcul d’indices </a></h5> 
                <p class="lead">
              
                <p> -Les indices de IB, IC et de BAI ont eu pour rôle de faciliter la distinction sur l’image les zones habitées et le sol nu.</p> 
                  <p> -IB : Indice de Brillance 
                  Cet indice présente une sensibilité certaine à l’humidité des sols, l’augmentation de la teneur en eau s’accompagne d’une diminution 
                  de la pureté et de la luminance de la couleur. Il permet de dissocier les surfaces minérales des couvertures végétales.
                      IB=√(R^2+〖NIR〗^2 ) </p>  
                  <p> -IC : Indice de Coloration du sol
                      IC= (R-V)/ (R+V) </p> 
                  <p> -BAI : Indice de zones Bâties
                      BAI= (B-NIR)/ (B+NIR) </p> 
                  <p> -L’indice d’eau 2 a permis de détecter les zones humides situées sur l’image.
                      NDVI= (PIR-IR)/ (PIR+IR) </p> 
                  </p> Dans le cadre de ce travail, le NDVI (Normalized Difference Vegetation Index) et le Ratio ont permis de mieux caractériser les différents 
                  types de végétations par rapport à l’intensité de leur activité chlorophyllienne pendant la saison sèche. 
                      NDVI= (NIR-R)/ (NIR+R) 
                      Ratio=NIR/ V   </p> 

                </p> 

